/**
 * Turns the extracted NFL schedule into the SQL that seeds `sport_games`.
 *
 * Kept as a script rather than hand-written SQL because 272 INSERT rows are 272
 * chances to fat-finger a team code, and because the schedule will be
 * re-extracted: weeks 16-18 of 2026 arrive from ESPN with no network assigned
 * and week 18 with all sixteen games on one placeholder kickoff, since the
 * league does not set those times until week 17 has been played.
 *
 *   node scripts/pickem-schedule-sql.mjs > supabase/migrations/0024_seed_chapa_pickem.sql
 *
 * The arithmetic below is the point of the script. 272 = 32 teams × 17 games ÷
 * 2, and every team plays exactly 17. If either fails this exits without
 * printing anything: a schedule that is quietly missing a week is a schedule
 * whose weeks silently score wrong, and finding that out in the seed costs
 * minutes where finding it out in November costs a client.
 */

import { readFileSync } from "node:fs";

const schedule = JSON.parse(
  readFileSync(new URL("./data/nfl-2026-schedule.json", import.meta.url), "utf8"),
);

const SEASON = schedule.season;
const weeks = Object.keys(schedule.weeks)
  .map(Number)
  .sort((a, b) => a - b);

const games = weeks.flatMap((week) =>
  schedule.weeks[String(week)].games.map((g) => ({ week, ...g })),
);

// ---------------------------------------------------------------------------
// The checks that must pass before anything is printed
// ---------------------------------------------------------------------------

const fail = (message) => {
  console.error(`schedule rejected: ${message}`);
  process.exit(1);
};

const teams = new Set(games.flatMap((g) => [g.a, g.h]));
if (teams.size !== 32) fail(`${teams.size} teams, expected 32`);

const played = new Map([...teams].map((t) => [t, 0]));
for (const g of games) {
  played.set(g.a, played.get(g.a) + 1);
  played.set(g.h, played.get(g.h) + 1);
}
const wrong = [...played].filter(([, n]) => n !== 17);
if (wrong.length) {
  fail(`teams not playing 17 games: ${wrong.map(([t, n]) => `${t}=${n}`).join(", ")}`);
}

if (games.length !== 272) fail(`${games.length} games, expected 272 (32 × 17 ÷ 2)`);
if (weeks.length !== 18) fail(`${weeks.length} weeks, expected 18`);

// A team cannot play twice in one week, which the unique constraint would catch
// on insert — but catching it here says which week rather than which row.
for (const week of weeks) {
  const seen = new Set();
  for (const g of games.filter((x) => x.week === week)) {
    for (const t of [g.a, g.h]) {
      if (seen.has(t)) fail(`${t} plays twice in week ${week}`);
      seen.add(t);
    }
  }
}

// ---------------------------------------------------------------------------
// SQL
// ---------------------------------------------------------------------------

const q = (value) =>
  value === null || value === undefined || value === "" ? "null" : `'${String(value).replace(/'/g, "''")}'`;

// ESPN writes "?" where the league has not assigned a broadcast yet. It reaches
// the column as NULL so the screen can say "cadena por definir" instead of
// printing a question mark at somebody.
const network = (tv) => (!tv || tv === "?" ? null : tv);

const rows = games
  .map(
    (g) =>
      `  (${g.week}, ${q(g.a)}, ${q(g.h)}, ${q(new Date(g.ts).toISOString())}::timestamptz, ` +
      `${q(network(g.tv))}, ${q(g.n)})`,
  )
  .join(",\n");

const unassigned = games.filter((g) => network(g.tv) === null).length;

process.stdout.write(`-- Seed: NFL ${SEASON} and the Chapa pick'em programme.
--
-- GENERATED by scripts/pickem-schedule-sql.mjs from scripts/data/nfl-2026-schedule.json.
-- Re-generate rather than edit; the script refuses to print a schedule that
-- does not satisfy 272 = 32 teams × 17 games ÷ 2 with every team at exactly 17.
--
-- ${games.length} games across ${weeks.length} weeks. ${unassigned} carry no network yet
-- (ESPN returns "?"), which is normal: the league assigns those broadcasts late.
--
-- Kickoffs are UTC. They are read in America/Ciudad_Juarez, which is Mountain
-- time synced to El Paso rather than Central like the rest of Chihuahua, and
-- daylight saving ends 1 November 2026 — mid-season. Week 1 shows MDT, week 9
-- onward MST. Formatting with Intl in that zone gets this right; subtracting a
-- fixed offset is wrong from week 9 on, by exactly the hour somebody needs to
-- not miss their lock.

-- ===========================================================================
-- The season
-- ===========================================================================

insert into public.sport_seasons (league, year, weeks)
values ('nfl', ${SEASON}, ${weeks.length})
on conflict (league, year) do update set weeks = excluded.weeks;

insert into public.sport_games (season_id, week, away, home, kickoff_at, network, venue_note)
select s.id, v.week, v.away, v.home, v.kickoff_at, v.network, v.venue_note
from public.sport_seasons s,
(values
${rows}
) as v(week, away, home, kickoff_at, network, venue_note)
where s.league = 'nfl' and s.year = ${SEASON}
on conflict (season_id, week, away, home) do update
  set kickoff_at = excluded.kickoff_at,
      network    = coalesce(excluded.network, public.sport_games.network),
      venue_note = excluded.venue_note;

-- The check that matters, run again against what actually landed. A seed that
-- half-applied is worse than one that failed.
do $$
declare v_count int;
begin
  select count(*) into v_count
  from public.sport_games g
  join public.sport_seasons s on s.id = g.season_id
  where s.league = 'nfl' and s.year = ${SEASON};
  if v_count <> 272 then
    raise exception 'sport_games has % rows for nfl ${SEASON}, expected 272', v_count;
  end if;
end $$;

-- ===========================================================================
-- Chapa
-- ===========================================================================
--
-- Copper and charcoal sampled from the files the client delivered. Only the
-- brand pair is themeable — action stays Supergana yellow, because the buttons
-- are the product's vocabulary and a tenant repainting them would be a tenant
-- forking the product (lib/tickets/theme.ts).
--
-- brand_ink is a separate value rather than a darkened brand: #D0765E is 2.6:1
-- on cream, which fails even the large-text bar, so body copy needs its own
-- darker tone. Guessing "darken until it passes" produces mud.

insert into public.organizations (slug, name, theme)
values (
  'chapa',
  'Chapa Carnes & Cantina',
  jsonb_build_object(
    'logo_url', '/brands/chapa/chapa-emblema-256.png',
    'logo_alt', 'Chapa Carnes & Cantina',
    'brand', '#d0765e',
    'brand_ink', '#8c3f2b',
    'powered_by', true
  )
)
on conflict (slug) do update
  set name = excluded.name, theme = excluded.theme;

-- Draft until launch day. The timezone is the tenant's clock and the reason
-- there is no display_tz on the season: the league's calendar is shared, the
-- clock it is read in is not.
--
-- profile_fields turns off everything a US receipt promotion needs and a
-- Mexican pick'em does not. The trigger in 0021 enforces the other half — a
-- pickem participant without a phone or an alias cannot be written at all.
--
-- rehearsal 'anyone' lets this draft programme accept picks so the client can
-- walk it end to end before the season opens. IT COMES OFF ON LAUNCH DAY, in
-- the same edit that sets status to 'live' — leaving it on would mean a live
-- programme with a second, wider door into it.
insert into public.campaigns (org_id, slug, name, module, status, locales, config)
select o.id, 'chapa-pickem-2026', 'NFL Pick''em by Chapa', 'pickem', 'draft',
  array['es'],
  jsonb_build_object(
    'timezone', 'America/Ciudad_Juarez',
    'profile_fields', jsonb_build_object('phone', 'required', 'zip', 'off', 'state', 'off'),
    'rehearsal', 'anyone'
  )
from public.organizations o
where o.slug = 'chapa'
on conflict (slug) do update
  set name = excluded.name, config = excluded.config;

-- The three branches, verified against Chapa's public sources.
--
-- promo_weeks: 11 is the Mexico City game and 12 falls on Thanksgiving. Both
-- are full-table occasions already, which is what makes them worth doubling —
-- a double week on a dead Sunday spends the lever without moving anybody.
insert into public.pickem_programs (campaign_id, season_id, open_week, venues, promo_weeks)
select c.id, s.id, 1,
  array['Chapa Prime', 'Chapa Gómez', 'Chapa Zaragoza'],
  array[11, 12]
from public.campaigns c, public.sport_seasons s
where c.slug = 'chapa-pickem-2026' and s.league = 'nfl' and s.year = ${SEASON}
on conflict (campaign_id) do update
  set season_id = excluded.season_id,
      venues = excluded.venues,
      promo_weeks = excluded.promo_weeks;
`);
